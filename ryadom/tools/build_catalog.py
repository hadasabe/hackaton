# -*- coding: utf-8 -*-
"""Build the local catalogue from official coordinates and reviewed editorial copy."""
import json
from pathlib import Path

PLACES = [('conservatory', 'Саратовская консерватория', 'Архитектура', 'Проспект Столыпина, 1'), ('chernyshevsky', 'Памятник Чернышевскому', 'История', 'Улица Радищева, 29'), ('lipki', 'Сад «Липки»', 'Природа', 'Улица Соборная'), ('radishchev', 'Радищевский музей', 'Искусство', 'Улица Радищева, 39'), ('utoli', 'Храм «Утоли моя печали»', 'Архитектура', 'Улица Волжская, 38'), ('schmidt', 'Особняк Шмидта', 'Архитектура', 'Улица Волжская, 32'), ('fedin', 'Музей Константина Федина', 'Искусство', 'Улица Чернышевского, 154'), ('embankment', 'Набережная Космонавтов', 'Природа', 'Набережная Космонавтов'), ('local-history', 'Музей краеведения', 'История', 'Улица Лермонтова, 34'), ('trinity', 'Свято-Троицкий собор', 'Архитектура', 'Улица Московская, 6'), ('book-house', 'Дом книги', 'Архитектура', 'Улица Вольская, 81'), ('volga-hotel', 'Гостиница «Волга»', 'Архитектура', 'Проспект Столыпина, 34'), ('circus', 'Цирк братьев Никитиных', 'Искусство', 'Улица Чапаева, 61'), ('estate', 'Музей-усадьба Чернышевского', 'История', 'Улица Чернышевского, 142'), ('cranes', 'Мемориал «Журавли»', 'История', 'Соколовая гора'), ('city-park', 'Городской парк', 'Природа', 'Улица Чернышевского, 81/83')]


def build():
    coordinates = json.loads(Path('data/coordinates.json').read_text(encoding='utf-8-sig'))
    editorial = json.loads(Path('data/editorial.json').read_text(encoding='utf-8-sig'))
    photo_path = Path('data/photos.json')
    photos = json.loads(photo_path.read_text(encoding='utf-8-sig')) if photo_path.exists() else {}
    gallery_path = Path('data/galleries.json')
    galleries = json.loads(gallery_path.read_text(encoding='utf-8-sig')) if gallery_path.exists() else {}
    assert len(coordinates) == len(PLACES)
    assert set(editorial) == {row[0] for row in PLACES}
    data = []
    for source, (id_, name, category, address) in zip(coordinates, PLACES):
        assert source['lat'] and source['lng']
        copy = editorial[id_]
        assert all(copy.get(field) for field in ('description', 'story', 'era', 'lookFor'))
        sources = [dict(title='Туристический портал Саратова', url=source['source']), *copy['sources']]
        photo = photos.get(id_)
        data.append(dict(id=id_, name=name, category=category, address=address,
                         description=copy['description'], story=copy['story'], era=copy['era'],
                         lookFor=copy['lookFor'], sources=sources,
                         lat=source['lat'], lng=source['lng'], source=source['source'], verified='2026-11-20',
                         glyph='leaf' if category=='Природа' else 'building' if category in ('Архитектура','Искусство') else 'pin',
                         image=photo['src'] if photo else None, photo=photo, audio=None))
    known = {p['id'] for p in data}
    for extra_path in (Path('data/additional-places.json'), Path('data/art-places.json')):
        if not extra_path.exists():
            continue
        extras = json.loads(extra_path.read_text(encoding='utf-8-sig'))
        for place in extras:
            assert place['id'] not in known, place['id']
            assert all(place.get(k) for k in ('name', 'address', 'description', 'story', 'source', 'lat', 'lng'))
            known.add(place['id'])
            photo = photos.get(place['id']) or place.get('photo')
            data.append(dict(place, image=photo['src'] if photo else None, photo=photo,
                             glyph='leaf' if place['category']=='Природа' else 'pin' if place['category']=='История' else 'building',
                             audio=None))
    assert set(galleries).issubset(known), 'Gallery refers to an unknown place'
    for place in data:
        gallery = []
        for photo in [place.get('photo'), *galleries.get(place['id'], [])]:
            if photo and photo['src'] not in {item['src'] for item in gallery}:
                assert Path(photo['src']).is_file(), photo['src']
                gallery.append(photo)
        place['gallery'] = gallery
    Path('data').mkdir(exist_ok=True)
    Path('data/places.js').write_text("/* Reviewed catalogue; generated by tools/build_catalog.py. */\n(function(root){\nconst data = "+json.dumps(data, ensure_ascii=False, indent=2)+";\nif(typeof module==='object'&&module.exports)module.exports=data;else root.RYADOM_PLACES=data;\n})(typeof globalThis!=='undefined'?globalThis:this);\n",encoding='utf-8')
    print(f'Built {len(data)} places; {sum(bool(p["photo"]) for p in data)} main photos; {sum(len(p["gallery"]) for p in data)} unique gallery photos')

if __name__=='__main__':build()
